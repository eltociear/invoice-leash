// Real ML-DSA-87 fixtures for the Foundry tests (test/InvoiceDesk.t.sol).
//
// Local EVMs have no QoreChain PQC precompile, so the tests install a stand-in at 0x…0a01 that
// answers from this file: every (public key, signature, message) tuple below was checked HERE with
// real ML-DSA-87 (@qorechain/sdk pqcVerify), and the stand-in returns exactly that answer. Tuples
// not in the file get `false` (fail closed). Keys come from fixed seeds and signing is
// deterministic (FIPS 204, rnd = 0), so `npm run fixtures` reproduces this file byte for byte.
import { writeFileSync, mkdirSync } from "node:fs";
import { generatePqcKeypair, pqcSign, pqcVerify } from "@qorechain/sdk";
import { keccak256, toUtf8Bytes, hexlify } from "ethers";
import { invoiceMessage } from "../lib/invoices.mjs";

const seed = (s) => Uint8Array.from(Buffer.from(keccak256(toUtf8Bytes(s)).slice(2), "hex"));
const keys = { hostline: generatePqcKeypair(seed("fixture:hostline")), tokenwell: generatePqcKeypair(seed("fixture:tokenwell")), mallory: generatePqcKeypair(seed("fixture:mallory")) };
// Fixed addresses the Solidity test uses (desk placed with deployCodeTo; chain id set to 9800).
const A = {
  desk: "0x00000000000000000000000000000000DE5C0001", desk2: "0x00000000000000000000000000000000DE5C0002",
  payer: "0x0000000000000000000000000000000000PA1E00".replace("PA1E", "0A1E"), payer2: "0x0000000000000000000000000000000000000B0B",
  hostline: "0x000000000000000000000000000000000000H057".replace("H057", "4057"), tokenwell: "0x0000000000000000000000000000000000007011", mallory: "0x000000000000000000000000000000000000BAD1",
};
const due = 1830297600; // 2028-01-01
const base = { desk: A.desk, payer: A.payer, vendor: A.hostline, amountWei: 800000000000000000n, id: keccak256(toUtf8Bytes("HOSTLINE-0042")), dueBy: due };
const msg = (o) => invoiceMessage({ ...base, ...o });
const sign = (who, o) => pqcSign(keys[who].secretKey, msg(o));

const genuine = sign("hostline", {});
const flip = Uint8Array.from(genuine); flip[1234] ^= 0x10;
const cases = [];
const add = (name, pub, signature, fields) => {
  const m = msg(fields);
  cases.push({ name, pubkey: hexlify(keys[pub].publicKey), signature: hexlify(signature), message: hexlify(m), valid: pqcVerify(keys[pub].publicKey, m, signature),
    payer: fields.payer ?? base.payer, vendor: fields.vendor ?? base.vendor, amount: String(fields.amountWei ?? base.amountWei), id: fields.id ?? base.id, dueBy: fields.dueBy ?? base.dueBy, desk: fields.desk ?? base.desk });
};
add("genuine", "hostline", genuine, {});
add("forged_by_mallory_as_hostline", "hostline", sign("mallory", {}), {});
add("amount_edited", "hostline", genuine, { amountWei: 950000000000000000n });
add("amount_plus_one_wei", "hostline", genuine, { amountWei: 800000000000000001n });
add("payee_swapped_to_tokenwell", "tokenwell", genuine, { vendor: A.tokenwell });
add("other_payer", "hostline", genuine, { payer: A.payer2 });
add("due_extended", "hostline", genuine, { dueBy: due + 86400 });
add("other_invoice_id", "hostline", genuine, { id: keccak256(toUtf8Bytes("HOSTLINE-0043")) });
add("other_desk", "hostline", genuine, { desk: A.desk2 });
add("one_bit_flipped", "hostline", flip, {});
add("mallory_own_invoice", "mallory", sign("mallory", { vendor: A.mallory, amountWei: 600000000000000000n }), { vendor: A.mallory, amountWei: 600000000000000000n });
add("tokenwell_genuine", "tokenwell", sign("tokenwell", { vendor: A.tokenwell, amountWei: 500000000000000000n, id: keccak256(toUtf8Bytes("TOKENWELL-7781")) }), { vendor: A.tokenwell, amountWei: 500000000000000000n, id: keccak256(toUtf8Bytes("TOKENWELL-7781")) });
// The same genuine invoice addressed to the second payer, signed for it (per-payer approvals and replay).
add("genuine_for_payer2", "hostline", sign("hostline", { payer: A.payer2 }), { payer: A.payer2 });
// Chain id 1 instead of 9800: built by hand because invoiceMessage() pins 9800.
{
  const { AbiCoder } = await import("ethers");
  const m = AbiCoder.defaultAbiCoder().encode(["bytes32", "uint256", "address", "address", "address", "uint256", "bytes32", "uint64"],
    [keccak256(toUtf8Bytes("LEASH-INVOICE-v1")), 1, base.desk, base.payer, base.vendor, base.amountWei, base.id, base.dueBy]);
  const mb = Uint8Array.from(Buffer.from(m.slice(2), "hex"));
  cases.push({ name: "message_for_chain_1", pubkey: hexlify(keys.hostline.publicKey), signature: hexlify(genuine), message: m, valid: pqcVerify(keys.hostline.publicKey, mb, genuine), note: "the genuine signature checked against the chain-1 message" });
}

const expectValid = new Set(["genuine", "mallory_own_invoice", "tokenwell_genuine", "genuine_for_payer2"]);
for (const c of cases) if (c.valid !== expectValid.has(c.name)) throw new Error(`fixture ${c.name}: real ML-DSA-87 says ${c.valid}`);
const out = { note: "Generated by test/fixtures.mjs with real ML-DSA-87 (@qorechain/sdk). Do not edit.", chainId: 9800, addresses: A,
  keys: Object.fromEntries(Object.entries(keys).map(([k, v]) => [k, hexlify(v.publicKey)])), cases };
mkdirSync(new URL("./fixtures/", import.meta.url), { recursive: true });
writeFileSync(new URL("./fixtures/mldsa.json", import.meta.url), JSON.stringify(out, null, 1) + "\n");
console.log(`test/fixtures/mldsa.json: ${cases.length} cases, ${cases.filter((c) => c.valid).length} valid under real ML-DSA-87`);

// ---------------------------------------------------------------- v2 (currency in the signed bytes)
{
  const { invoiceMessageV2 } = await import("../lib/invoices.mjs");
  const T = { fusd: "0x000000000000000000000000000000000000F05D", other: "0x0000000000000000000000000000000000000E7C", zero: "0x0000000000000000000000000000000000000000" };
  const b2 = { desk: A.desk, payer: A.payer, vendor: A.hostline, token: T.fusd, amount: 80000000n, id: keccak256(toUtf8Bytes("HOSTLINE-V2-0042")), dueBy: due };
  const m2 = (o) => invoiceMessageV2({ ...b2, ...o });
  const s2 = (who, o) => pqcSign(keys[who].secretKey, m2(o));
  const g2 = s2("hostline", {});
  const f2 = Uint8Array.from(g2); f2[999] ^= 0x01;
  const cases2 = [];
  const add2 = (name, pub, signature, fields) => {
    const m = m2(fields);
    cases2.push({ name, pubkey: hexlify(keys[pub].publicKey), signature: hexlify(signature), message: hexlify(m), valid: pqcVerify(keys[pub].publicKey, m, signature),
      payer: fields.payer ?? b2.payer, vendor: fields.vendor ?? b2.vendor, token: fields.token ?? b2.token, amount: String(fields.amount ?? b2.amount), id: fields.id ?? b2.id, dueBy: fields.dueBy ?? b2.dueBy, desk: fields.desk ?? b2.desk });
  };
  add2("genuine_fusd", "hostline", g2, {});
  add2("forged_by_mallory_as_hostline", "hostline", s2("mallory", {}), {});
  add2("amount_edited", "hostline", g2, { amount: 95000000n });
  add2("paid_in_qor_instead", "hostline", g2, { token: T.zero });
  add2("paid_in_other_token", "hostline", g2, { token: T.other });
  add2("payee_swapped_to_tokenwell", "tokenwell", g2, { vendor: A.tokenwell });
  add2("other_payer", "hostline", g2, { payer: A.payer2 });
  add2("other_desk", "hostline", g2, { desk: A.desk2 });
  add2("due_extended", "hostline", g2, { dueBy: due + 86400 });
  add2("one_bit_flipped", "hostline", f2, {});
  add2("mallory_own_invoice", "mallory", s2("mallory", { vendor: A.mallory, amount: 60000000n }), { vendor: A.mallory, amount: 60000000n });
  add2("genuine_native_qor", "hostline", s2("hostline", { token: T.zero, amount: 800000000000000000n, id: keccak256(toUtf8Bytes("HOSTLINE-V2-QOR")) }), { token: T.zero, amount: 800000000000000000n, id: keccak256(toUtf8Bytes("HOSTLINE-V2-QOR")) });
  add2("tokenwell_genuine_fusd", "tokenwell", s2("tokenwell", { vendor: A.tokenwell, amount: 60000000n, id: keccak256(toUtf8Bytes("TOKENWELL-V2-8781")) }), { vendor: A.tokenwell, amount: 60000000n, id: keccak256(toUtf8Bytes("TOKENWELL-V2-8781")) });
  const valid2 = new Set(["genuine_fusd", "mallory_own_invoice", "genuine_native_qor", "tokenwell_genuine_fusd"]);
  for (const c of cases2) if (c.valid !== valid2.has(c.name)) throw new Error(`v2 fixture ${c.name}: real ML-DSA-87 says ${c.valid}`);
  writeFileSync(new URL("./fixtures/mldsa-v2.json", import.meta.url), JSON.stringify({ note: out.note, chainId: 9800, addresses: A, tokens: T, keys: out.keys, cases: cases2 }, null, 1) + "\n");
  console.log(`test/fixtures/mldsa-v2.json: ${cases2.length} cases, ${cases2.filter((c) => c.valid).length} valid under real ML-DSA-87`);

  // ---------------------------------------------------------------- v3 (same signed format; V3-only cases added)
  // Every v2 case, plus invoices that exercise what V3 changes. All are genuinely signed: V3 refuses some
  // of them (zero amount, a fee-taking token) for reasons other than the signature.
  const T3 = { ...T, fee: "0x000000000000000000000000000000000000FEE0" };
  const sameId = { vendor: A.tokenwell, amount: 50000000n }; // Tokenwell, using Hostline's invoice number
  add2("tokenwell_same_id_as_hostline", "tokenwell", s2("tokenwell", sameId), sameId);
  const zero = { amount: 0n, id: keccak256(toUtf8Bytes("HOSTLINE-V3-ZERO")) };
  add2("zero_amount", "hostline", s2("hostline", zero), zero);
  const feeTok = { token: T3.fee, id: keccak256(toUtf8Bytes("HOSTLINE-V3-FEE")) };
  add2("fee_taking_token", "hostline", s2("hostline", feeTok), feeTok);
  const valid3 = new Set([...valid2, "tokenwell_same_id_as_hostline", "zero_amount", "fee_taking_token"]);
  for (const c of cases2) if (c.valid !== valid3.has(c.name)) throw new Error(`v3 fixture ${c.name}: real ML-DSA-87 says ${c.valid}`);
  writeFileSync(new URL("./fixtures/mldsa-v3.json", import.meta.url), JSON.stringify({ note: out.note, chainId: 9800, addresses: A, tokens: T3, keys: out.keys, cases: cases2 }, null, 1) + "\n");
  console.log(`test/fixtures/mldsa-v3.json: ${cases2.length} cases, ${cases2.filter((c) => c.valid).length} valid under real ML-DSA-87`);

  // ---------------------------------------------------------------- v4 (V3 + the agent's own ML-DSA-87 signature)
  // The agent signer's key signs agentMessage(...) for every v3 case, for both test agents (the unit tests'
  // and the invariant handler's), so a test fails on the check it is about, not on the agent's signature.
  const { AbiCoder } = await import("ethers");
  const signer = generatePqcKeypair(seed("fixture:agentsigner"));
  const AGENT_DOMAIN = keccak256(toUtf8Bytes("LEASH-AGENT-PAY-v1"));
  const agentMsg = (c, agent) => Uint8Array.from(Buffer.from(AbiCoder.defaultAbiCoder().encode(
    ["bytes32", "uint256", "address", "address", "address", "address", "address", "uint256", "bytes32"],
    [AGENT_DOMAIN, 9800, c.desk, c.payer, agent, c.vendor, c.token, c.amount, c.id]).slice(2), "hex"));
  const AGENTS = ["0x000000000000000000000000000000000000A9E7", "0x00000000000000000000000000000000000A6E47"];
  const agentSigs = {};
  for (const agent of AGENTS) agentSigs[agent] = cases2.map((c) => { const m = agentMsg(c, agent), sg = pqcSign(signer.secretKey, m); return { name: c.name, message: hexlify(m), signature: hexlify(sg), valid: pqcVerify(signer.publicKey, m, sg) }; });
  const g = cases2.find((c) => c.name === "genuine_fusd"), gm = agentMsg(g, AGENTS[0]), foreign = pqcSign(keys.mallory.secretKey, gm);
  // Genuine vendor invoices that differ from genuine_fusd in one field only. The agent's signature for
  // genuine_fusd must not authorise any of them: a corrected amount, a second invoice for the same amount,
  // a reissue in another token. (For each, Hostline's own signature is valid.)
  const extras = [
    ["hostline_corrected_95", { amount: 95000000n }],
    ["hostline_second_invoice_same_amount", { id: keccak256(toUtf8Bytes("HOSTLINE-V2-0044")) }],
    ["hostline_reissued_in_other_token", { token: T.other }],
  ].map(([name, o]) => { const m = m2(o), sg = s2("hostline", o); return { name, pubkey: hexlify(keys.hostline.publicKey), signature: hexlify(sg), message: hexlify(m), valid: pqcVerify(keys.hostline.publicKey, m, sg),
    payer: b2.payer, vendor: b2.vendor, token: o.token ?? b2.token, amount: String(o.amount ?? b2.amount), id: o.id ?? b2.id, dueBy: b2.dueBy }; });
  if (extras.some((x) => !x.valid)) throw new Error("v4 extras: real ML-DSA-87 disagrees");
  const v4 = { note: out.note, chainId: 9800, addresses: A, tokens: T3, keys: { ...out.keys, agentsigner: hexlify(signer.publicKey) }, cases: cases2, extras, agentSigs,
    foreign: { name: "genuine_fusd signed by a key that is not the agent signer's", message: hexlify(gm), signature: hexlify(foreign), valid: pqcVerify(signer.publicKey, gm, foreign) } };
  if (Object.values(agentSigs).flat().some((x) => !x.valid) || v4.foreign.valid) throw new Error("v4 agent signatures: real ML-DSA-87 disagrees");
  writeFileSync(new URL("./fixtures/mldsa-v4.json", import.meta.url), JSON.stringify(v4, null, 1) + "\n");
  console.log(`test/fixtures/mldsa-v4.json: ${cases2.length} cases, ${AGENTS.length * cases2.length} agent signatures (real ML-DSA-87), 1 foreign`);

  // ---------------------------------------------------------------- v5 (the agent signs the whole invoice, its vendor signature and a deadline)
  // The same v3 cases. The agent signer signs agentMessage(payer, agent, keccak256(invoiceMessage(...)),
  // keccak256(vendor signature), validUntil) for each, for both test agents. validUntil is fixed (the file
  // must reproduce byte for byte) and lies a week after the fixtures' due date, so the older tests (past
  // due, limits, ...) still reach the check they are about; the tests warp past it to test the expiry.
  const { agentMessageV5 } = await import("../lib/invoices.mjs");
  const VALID_UNTIL = due + 7 * 86400; // 2028-01-08
  const AGENT_DOMAIN_V5 = keccak256(toUtf8Bytes("LEASH-AGENT-PAY-v2"));
  const agentMsg5 = (c, agent, validUntil = VALID_UNTIL) => {
    const digest = keccak256(m2({ desk: c.desk ?? b2.desk, payer: c.payer, vendor: c.vendor, token: c.token, amount: BigInt(c.amount), id: c.id, dueBy: c.dueBy }));
    const m = Uint8Array.from(Buffer.from(AbiCoder.defaultAbiCoder().encode(
      ["bytes32", "uint256", "address", "address", "address", "bytes32", "bytes32", "uint64"],
      [AGENT_DOMAIN_V5, 9800, c.desk ?? b2.desk, c.payer, agent, digest, keccak256(c.signature), validUntil]).slice(2), "hex"));
    // the same bytes as lib/invoices.mjs agentMessageV5 (what desk.mjs signs)
    const lib = agentMessageV5({ desk: c.desk ?? b2.desk, payer: c.payer, agent, invoice: c, validUntil });
    if (hexlify(lib) !== hexlify(m)) throw new Error(`v5: lib agentMessageV5 disagrees for ${c.name}`);
    return m;
  };
  const agentSigs5 = {};
  for (const agent of AGENTS) agentSigs5[agent] = cases2.map((c) => { const m = agentMsg5(c, agent), sg = pqcSign(signer.secretKey, m); return { name: c.name, message: hexlify(m), signature: hexlify(sg), valid: pqcVerify(signer.publicKey, m, sg) }; });
  const g5m = agentMsg5(g, AGENTS[0]), foreign5 = pqcSign(keys.mallory.secretKey, g5m);
  // V4's extras, plus the genuine invoice reissued by Hostline with a due date 30 days later (genuinely signed).
  const reissue = { dueBy: due + 30 * 86400 };
  const extras5 = [...extras, ...[["hostline_reissued_due_later", reissue]].map(([name, o]) => { const m = m2(o), sg = s2("hostline", o); return { name, pubkey: hexlify(keys.hostline.publicKey), signature: hexlify(sg), message: hexlify(m), valid: pqcVerify(keys.hostline.publicKey, m, sg),
    payer: b2.payer, vendor: b2.vendor, token: b2.token, amount: String(b2.amount), id: b2.id, dueBy: o.dueBy }; })];
  if (extras5.some((x) => !x.valid)) throw new Error("v5 extras: real ML-DSA-87 disagrees");
  // The agent's own signatures for the extras (agent 0xA9E7): each genuinely payable by the agent on its own.
  const extraAgentSigs = extras5.map((x) => { const m = agentMsg5(x, AGENTS[0]), sg = pqcSign(signer.secretKey, m); return { name: x.name, message: hexlify(m), signature: hexlify(sg), valid: pqcVerify(signer.publicKey, m, sg) }; });
  // What the new bindings refuse, each as presented to the desk: the invoice fields and vendor signature in
  // calldata, the agent signature attached, the validUntil in calldata, and the agent message the desk builds
  // from them. `valid` is real ML-DSA-87 on (agent signer's key, agentSignature, message).
  const sigOf = (name) => agentSigs5[AGENTS[0]][cases2.findIndex((c) => c.name === name)].signature;
  const forged = cases2.find((c) => c.name === "forged_by_mallory_as_hostline");
  const reissued = extras5.find((x) => x.name === "hostline_reissued_due_later");
  const binding = (name, note, inv, agentSignature, validUntil, at) => {
    const m = agentMsg5(inv, AGENTS[0], validUntil);
    return { name, note, payer: inv.payer, vendor: inv.vendor, token: inv.token, amount: String(inv.amount), id: inv.id, dueBy: inv.dueBy, signature: inv.signature,
      agentSignature, validUntil, ...(at ? { at } : {}), message: hexlify(m), valid: pqcVerify(signer.publicKey, m, Uint8Array.from(Buffer.from(agentSignature.slice(2), "hex"))) };
  };
  const bindings = [
    binding("forged_copy_agent_sig_on_genuine_invoice", "the agent signature made for forged_by_mallory_as_hostline (same fields, a bad vendor signature), presented with genuine_fusd's genuine vendor signature",
      g, sigOf(forged.name), VALID_UNTIL),
    binding("old_agent_sig_on_due_later_reissue", "genuine_fusd's agent signature, presented with Hostline's genuine reissue of the same invoice due 30 days later",
      reissued, sigOf("genuine_fusd"), VALID_UNTIL),
    binding("validUntil_changed_in_calldata", "genuine_fusd's agent signature, presented with validUntil + 1",
      g, sigOf("genuine_fusd"), VALID_UNTIL + 1),
    binding("after_validUntil", "genuine_fusd's agent signature, unchanged and valid, presented one second after validUntil: the desk refuses it by time",
      g, sigOf("genuine_fusd"), VALID_UNTIL, VALID_UNTIL + 1),
  ];
  const expect5 = { forged_copy_agent_sig_on_genuine_invoice: false, old_agent_sig_on_due_later_reissue: false, validUntil_changed_in_calldata: false, after_validUntil: true };
  for (const b of bindings) if (b.valid !== expect5[b.name]) throw new Error(`v5 binding ${b.name}: real ML-DSA-87 says ${b.valid}`);
  const v5 = { note: out.note, chainId: 9800, addresses: A, tokens: T3, keys: { ...out.keys, agentsigner: hexlify(signer.publicKey) }, validUntil: VALID_UNTIL, cases: cases2, extras: extras5, extraAgentSigs, agentSigs: agentSigs5,
    foreign: { name: "genuine_fusd signed by a key that is not the agent signer's", message: hexlify(g5m), signature: hexlify(foreign5), valid: pqcVerify(signer.publicKey, g5m, foreign5) }, bindings };
  if ([...Object.values(agentSigs5).flat(), ...extraAgentSigs].some((x) => !x.valid) || v5.foreign.valid) throw new Error("v5 agent signatures: real ML-DSA-87 disagrees");
  writeFileSync(new URL("./fixtures/mldsa-v5.json", import.meta.url), JSON.stringify(v5, null, 1) + "\n");
  console.log(`test/fixtures/mldsa-v5.json: ${cases2.length} cases, ${AGENTS.length * cases2.length} agent signatures (real ML-DSA-87), ${extraAgentSigs.length} for the extras, 1 foreign, ${bindings.length} bindings`);
}
