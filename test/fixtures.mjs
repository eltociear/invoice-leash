// Real ML-DSA-87 fixtures for the Foundry tests (test/InvoiceDesk.t.sol).
//
// Local EVMs have no QoreChain PQC precompile, so the tests install a stand-in at 0x…0a01 that
// answers from this file: every (public key, signature, message) tuple below was checked HERE with
// real ML-DSA-87 (@qorechain/sdk pqcVerify), and the stand-in returns exactly that answer. Tuples
// not in the file get `false` (fail closed). Keys come from fixed seeds and signing is
// deterministic (FIPS 204, rnd = 0), so `npm run fixtures` reproduces this file byte for byte.
import { writeFileSync, mkdirSync } from "node:fs";
import { generatePqcKeypair, pqcSign, pqcVerify } from "@qorechain/sdk";
import { keccak256, toUtf8Bytes, hexlify } from "ethers";
import { invoiceMessage } from "../lib/invoices.mjs";

const seed = (s) => Uint8Array.from(Buffer.from(keccak256(toUtf8Bytes(s)).slice(2), "hex"));
const keys = { hostline: generatePqcKeypair(seed("fixture:hostline")), tokenwell: generatePqcKeypair(seed("fixture:tokenwell")), mallory: generatePqcKeypair(seed("fixture:mallory")) };
// Fixed addresses the Solidity test uses (desk placed with deployCodeTo; chain id set to 9800).
const A = {
  desk: "0x00000000000000000000000000000000DE5C0001", desk2: "0x00000000000000000000000000000000DE5C0002",
  payer: "0x0000000000000000000000000000000000PA1E00".replace("PA1E", "0A1E"), payer2: "0x0000000000000000000000000000000000000B0B",
  hostline: "0x000000000000000000000000000000000000H057".replace("H057", "4057"), tokenwell: "0x0000000000000000000000000000000000007011", mallory: "0x000000000000000000000000000000000000BAD1",
};
const due = 1830297600; // 2028-01-01
const base = { desk: A.desk, payer: A.payer, vendor: A.hostline, amountWei: 800000000000000000n, id: keccak256(toUtf8Bytes("HOSTLINE-0042")), dueBy: due };
const msg = (o) => invoiceMessage({ ...base, ...o });
const sign = (who, o) => pqcSign(keys[who].secretKey, msg(o));

const genuine = sign("hostline", {});
const flip = Uint8Array.from(genuine); flip[1234] ^= 0x10;
const cases = [];
const add = (name, pub, signature, fields) => {
  const m = msg(fields);
  cases.push({ name, pubkey: hexlify(keys[pub].publicKey), signature: hexlify(signature), message: hexlify(m), valid: pqcVerify(keys[pub].publicKey, m, signature),
    payer: fields.payer ?? base.payer, vendor: fields.vendor ?? base.vendor, amount: String(fields.amountWei ?? base.amountWei), id: fields.id ?? base.id, dueBy: fields.dueBy ?? base.dueBy, desk: fields.desk ?? base.desk });
};
add("genuine", "hostline", genuine, {});
add("forged_by_mallory_as_hostline", "hostline", sign("mallory", {}), {});
add("amount_edited", "hostline", genuine, { amountWei: 950000000000000000n });
add("amount_plus_one_wei", "hostline", genuine, { amountWei: 800000000000000001n });
add("payee_swapped_to_tokenwell", "tokenwell", genuine, { vendor: A.tokenwell });
add("other_payer", "hostline", genuine, { payer: A.payer2 });
add("due_extended", "hostline", genuine, { dueBy: due + 86400 });
add("other_invoice_id", "hostline", genuine, { id: keccak256(toUtf8Bytes("HOSTLINE-0043")) });
add("other_desk", "hostline", genuine, { desk: A.desk2 });
add("one_bit_flipped", "hostline", flip, {});
add("mallory_own_invoice", "mallory", sign("mallory", { vendor: A.mallory, amountWei: 600000000000000000n }), { vendor: A.mallory, amountWei: 600000000000000000n });
add("tokenwell_genuine", "tokenwell", sign("tokenwell", { vendor: A.tokenwell, amountWei: 500000000000000000n, id: keccak256(toUtf8Bytes("TOKENWELL-7781")) }), { vendor: A.tokenwell, amountWei: 500000000000000000n, id: keccak256(toUtf8Bytes("TOKENWELL-7781")) });
// The same genuine invoice addressed to the second payer, signed for it (per-payer approvals and replay).
add("genuine_for_payer2", "hostline", sign("hostline", { payer: A.payer2 }), { payer: A.payer2 });
// Chain id 1 instead of 9800: built by hand because invoiceMessage() pins 9800.
{
  const { AbiCoder } = await import("ethers");
  const m = AbiCoder.defaultAbiCoder().encode(["bytes32", "uint256", "address", "address", "address", "uint256", "bytes32", "uint64"],
    [keccak256(toUtf8Bytes("LEASH-INVOICE-v1")), 1, base.desk, base.payer, base.vendor, base.amountWei, base.id, base.dueBy]);
  const mb = Uint8Array.from(Buffer.from(m.slice(2), "hex"));
  cases.push({ name: "message_for_chain_1", pubkey: hexlify(keys.hostline.publicKey), signature: hexlify(genuine), message: m, valid: pqcVerify(keys.hostline.publicKey, mb, genuine), note: "the genuine signature checked against the chain-1 message" });
}

const expectValid = new Set(["genuine", "mallory_own_invoice", "tokenwell_genuine", "genuine_for_payer2"]);
for (const c of cases) if (c.valid !== expectValid.has(c.name)) throw new Error(`fixture ${c.name}: real ML-DSA-87 says ${c.valid}`);
const out = { note: "Generated by test/fixtures.mjs with real ML-DSA-87 (@qorechain/sdk). Do not edit.", chainId: 9800, addresses: A,
  keys: Object.fromEntries(Object.entries(keys).map(([k, v]) => [k, hexlify(v.publicKey)])), cases };
mkdirSync(new URL("./fixtures/", import.meta.url), { recursive: true });
writeFileSync(new URL("./fixtures/mldsa.json", import.meta.url), JSON.stringify(out, null, 1) + "\n");
console.log(`test/fixtures/mldsa.json: ${cases.length} cases, ${cases.filter((c) => c.valid).length} valid under real ML-DSA-87`);

// ---------------------------------------------------------------- v2 (currency in the signed bytes)
{
  const { invoiceMessageV2 } = await import("../lib/invoices.mjs");
  const T = { fusd: "0x000000000000000000000000000000000000F05D", other: "0x0000000000000000000000000000000000000E7C", zero: "0x0000000000000000000000000000000000000000" };
  const b2 = { desk: A.desk, payer: A.payer, vendor: A.hostline, token: T.fusd, amount: 80000000n, id: keccak256(toUtf8Bytes("HOSTLINE-V2-0042")), dueBy: due };
  const m2 = (o) => invoiceMessageV2({ ...b2, ...o });
  const s2 = (who, o) => pqcSign(keys[who].secretKey, m2(o));
  const g2 = s2("hostline", {});
  const f2 = Uint8Array.from(g2); f2[999] ^= 0x01;
  const cases2 = [];
  const add2 = (name, pub, signature, fields) => {
    const m = m2(fields);
    cases2.push({ name, pubkey: hexlify(keys[pub].publicKey), signature: hexlify(signature), message: hexlify(m), valid: pqcVerify(keys[pub].publicKey, m, signature),
      payer: fields.payer ?? b2.payer, vendor: fields.vendor ?? b2.vendor, token: fields.token ?? b2.token, amount: String(fields.amount ?? b2.amount), id: fields.id ?? b2.id, dueBy: fields.dueBy ?? b2.dueBy, desk: fields.desk ?? b2.desk });
  };
  add2("genuine_fusd", "hostline", g2, {});
  add2("forged_by_mallory_as_hostline", "hostline", s2("mallory", {}), {});
  add2("amount_edited", "hostline", g2, { amount: 95000000n });
  add2("paid_in_qor_instead", "hostline", g2, { token: T.zero });
  add2("paid_in_other_token", "hostline", g2, { token: T.other });
  add2("payee_swapped_to_tokenwell", "tokenwell", g2, { vendor: A.tokenwell });
  add2("other_payer", "hostline", g2, { payer: A.payer2 });
  add2("other_desk", "hostline", g2, { desk: A.desk2 });
  add2("due_extended", "hostline", g2, { dueBy: due + 86400 });
  add2("one_bit_flipped", "hostline", f2, {});
  add2("mallory_own_invoice", "mallory", s2("mallory", { vendor: A.mallory, amount: 60000000n }), { vendor: A.mallory, amount: 60000000n });
  add2("genuine_native_qor", "hostline", s2("hostline", { token: T.zero, amount: 800000000000000000n, id: keccak256(toUtf8Bytes("HOSTLINE-V2-QOR")) }), { token: T.zero, amount: 800000000000000000n, id: keccak256(toUtf8Bytes("HOSTLINE-V2-QOR")) });
  const valid2 = new Set(["genuine_fusd", "mallory_own_invoice", "genuine_native_qor"]);
  for (const c of cases2) if (c.valid !== valid2.has(c.name)) throw new Error(`v2 fixture ${c.name}: real ML-DSA-87 says ${c.valid}`);
  writeFileSync(new URL("./fixtures/mldsa-v2.json", import.meta.url), JSON.stringify({ note: out.note, chainId: 9800, addresses: A, tokens: T, keys: out.keys, cases: cases2 }, null, 1) + "\n");
  console.log(`test/fixtures/mldsa-v2.json: ${cases2.length} cases, ${cases2.filter((c) => c.valid).length} valid under real ML-DSA-87`);
}
